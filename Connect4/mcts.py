### Implement Monte-Carlo Tree Search (MCTS), aided by the NN

from rules import init_board, legal_actions, place_piece, is_win, is_board_full

import numpy as np


'''
AlphaZero trains by teaching its neural network to think ahead;
training data is generated by simulating "thinking ahead" with a search tree,
which is analogous to actually thinking ahead. 
The hope is then that the neural network can internally learn how to think ahead, 
much more efficiently than with the search tree. 

The search tree expands positions into possible next moves at each step. 
Since the action space in Connect4 grows exponentially, 
MCTS prioritising actions that seem the most promising, according to the UCB score. 

PUCT combines the:
 - current neural network version's prediction on how promising a move / future state seems,
 - and how much that line of thought has already been explored.

Training can then compare the neural networks initial evaluation of a position / move, 
and the presumably more accurate evaluation after thinking through that line thoroughly. 
'''


class Node:
    # Initialize new node in search tree
    def __init__(self, current_player, state, parent, action, prior):
        self.current_player = current_player
        self.state = state
        self.parent = parent
        self.action = action
        self.prior = prior

        self.children = {}  # dict e.g. {0: Node(...), 1: Node(...)}
        self.visit_count = 0
        self.value = 0


    # Check if node has been expanded
    def is_expanded(self):
        return len(self.children) > 0


    # Check if node state is terminal (win / loss)
    def is_terminal(self):
        return (is_win(self.state, 1) or
                is_win(self.state, -1) or
                is_board_full(self.state))


    # Return value of terminal state
    def terminal_value(self):
        # If a player is handed a won state on their turn, they've lost
        # Otherwise the board must've been filled
        if is_win(self.state, -self.current_player):
            return -1
        return 0  # board is full


    # Expand the children of a node
    def expand(self, player, policy):
        for action in np.arange(7)[legal_actions(self.state)]:
            self.children[action] = Node(current_player=-self.current_player,
                                         state=place_piece(self.state, player, action),
                                         parent=self, action=action, prior=policy[action]
                                         )


    # Backpropagate evaluations up the tree
    def backup(self, value):
        node = self
        while node is not None:
            node.visit_count += 1
            node.value += value

            value = -value  # since a good position for one player is bad for the other
            node = node.parent


class MCTS:
    def __init__(self, model, exploration_rate=0.1):
        self.model = model  # board --> (policy, value)
        self.exploration_rate = exploration_rate

        # TODO: Make this initialisation flexible to any root
        board = init_board()
        self.root = Node(current_player=1, state=board, parent=None, action=0, prior=0)


    def simulate(self):
        # TODO: Make this flexible to any root
        node = self.root

        # 1. Selection
        def puct(node, child):
            # W/N + exploration_rate * child.prior * np.sqrt([siblings visit count sum]) / (1 + child.visit_count)
            # TODO: Fix redundant sum calculation
            siblings_visit_sum = sum([sibling.visit_count for sibling in node.children.values()])
            q = -child.value / child.visit_count if child.visit_count > 0 else 0  # flip value as player perspective changes
            u = self.exploration_rate * child.prior * (
                    np.sqrt(max(1, siblings_visit_sum)) / (1 + child.visit_count)
            )
            return q + u


        while node.is_expanded() and not node.is_terminal():
            node = max(
                node.children.values(),
                key=lambda child: puct(node, child)
            )

        # 2. Expansion, evaluation
        if node.is_terminal():
            value = node.terminal_value()
        else:
            # TODO: mask and normalize policy
            policy, value = self.model.forward(node.state)

            node.expand(node.current_player, policy)

        # 3. Backpropagation
        node.backup(value)



